pub fn t(key: &str, params: &[(&str, &str)], locale: &str) -> String {
    let loc = locale.to_lowercase();
    let base = loc.split('-').next().filter(|_| loc.contains('-'));
    let s = get_table(&loc)
        .and_then(|t| t.get(key).cloned())
        .or_else(|| {
            base.and_then(|b| get_table(b))
                .and_then(|t| t.get(key).cloned())
        })
        .or_else(|| get_table("en").and_then(|t| t.get(key).cloned()))
        .unwrap_or_else(|| key.to_string());
    let mut result = s;
    for (k, v) in params {
        result = result.replace(&format!("{{{k}}}"), v);
    }
    result
}

pub fn label(key: &str, language: &str) -> String {
    t(&format!("pdf.{key}"), &[], language)
}

pub fn unit_label(code: &str, language: &str) -> String {
    let s = t(&format!("unit.{code}"), &[], language);
    if s == format!("unit.{code}") {
        code.to_string()
    } else {
        s
    }
}

pub fn resolve_locale(locale: Option<&str>) -> String {
    locale
        .map(|s| s.to_string())
        .or_else(|| std::env::var("BUKIO_LOCALE").ok().filter(|s| !s.is_empty()))
        .unwrap_or_else(|| "en".to_string())
}

