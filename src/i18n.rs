use std::collections::HashMap;

type Table = HashMap<String, String>;

fn build_table(pairs: &[(&str, &str)]) -> Table {
    pairs
        .iter()
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect()
}

